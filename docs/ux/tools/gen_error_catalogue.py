"""Render docs/ux/error-catalogue.md from api/openapi.yaml + frontend/src/i18n/{vi,en}/translation.json.

frontend/src/i18n/{vi,en}/translation.json is the source of truth for wording; this script only lays them out so the
catalogue can never drift from what the UI shows. Checked by docs/ux/tools/test_docs.py.

    env -u PYTHONPATH uv run --no-project --python 3.12 --with pyyaml \
        python docs/ux/tools/gen_error_catalogue.py          # rewrite
    ... gen_error_catalogue.py --check                        # exit 1 if stale
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

FAMILIES = [
    ("General", "Chung", "bad_request", "service_unavailable"),
    ("Authentication", "Xác thực", "invalid_credentials", "email_taken"),
    ("Workspaces", "Workspace", "workspace_slug_taken", "quota_exceeded"),
    ("Datasets and uploads", "Dataset và tải lên", "dataset_name_taken", "archive_format_unsupported"),
    ("Runs", "Lượt train", "policy_unknown", "checkpoint_not_found"),
    ("Models and jobs", "Model và tác vụ", "model_not_ready", "job_not_cancellable"),
]


def _load(repo: Path, locale: str) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(
        (repo / "frontend" / "src" / "i18n" / locale / "translation.json").read_text(encoding="utf-8")
    )
    return data


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _key(value: str) -> str:
    snake = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", value).lower()
    return re.sub(r"[^a-z0-9]+", "_", snake).strip("_")


def _table(rows: list[tuple[str, str, str]], head: str = "| code | vi | en |") -> list[str]:
    out = [head, "|---|---|---|"]
    out += [f"| `{k}` | {_cell(v)} | {_cell(e)} |" for k, v, e in rows]
    return out + [""]


def render(repo: Path) -> str:
    spec = yaml.safe_load((repo / "api" / "openapi.yaml").read_text(encoding="utf-8"))
    schemas = spec["components"]["schemas"]
    codes: list[str] = schemas["ErrorCode"]["enum"]
    status = dict(re.findall(r"([a-z_]+) \[(\d{3})\]", schemas["ErrorCode"]["description"]))
    tr = {loc: _load(repo, loc) for loc in ("vi", "en")}
    err = {loc: tr[loc]["errors"] for loc in tr}

    out: list[str] = [
        "# Error-message catalogue / Danh mục thông điệp lỗi",
        "",
        "<!-- GENERATED by docs/ux/tools/gen_error_catalogue.py from api/openapi.yaml and",
        "     frontend/src/i18n/{vi,en}/translation.json. Do not edit by hand: change the JSON and",
        "     re-run. -->",
        "",
        f"Contract `api/openapi.yaml` v{spec['info']['version']}: **{len(codes)}** `ErrorCode` values, "
        f"{len(schemas['ValidationIssue']['properties']['code']['enum'])} `ValidationIssue.code`, "
        f"{len(schemas['RunErrorCode']['enum'])} `RunErrorCode`, "
        f"{len(schemas['RunWarningEvent']['properties']['code']['enum'])} run warning codes. "
        "Every one has vi + en copy (enforced by `frontend/src/lib/i18n.test.ts`).",
        "",
        "How the UI uses it (see `docs/ux/copy-deck.md` §4):",
        "",
        "* Branch on `Problem.code`, never on `title`/`detail`. `src/lib/errors.ts` maps the code to",
        "  `errors.<code>` (one actionable sentence: what happened + what to do next) and passes",
        "  `Problem.params` plus `retry_after_s` as interpolation values.",
        "* `errors.request_id` shows `Problem.request_id`; unknown codes (newer server) fall back to",
        "  `errors.unknown_error`.",
        "* `FieldError.code` → `field_errors.<code>` next to the field (fallback: `errors.<code>`).",
        "",
    ]
    idx = {c: i for i, c in enumerate(codes)}
    covered: set[str] = set()
    for en_name, vi_name, first, last in FAMILIES:
        out += [f"## {en_name} / {vi_name}", "", "| code | HTTP | vi | en |", "|---|---|---|---|"]
        for code in codes[idx[first] : idx[last] + 1]:
            covered.add(code)
            out.append(
                f"| `{code}` | {status.get(code, '?')} | {_cell(err['vi'][code])} | {_cell(err['en'][code])} |"
            )
        out.append("")
    assert covered == set(codes), set(codes) - covered

    out += ["## Field errors (`FieldError.code`) / Lỗi từng trường", ""]
    out += _table([(k, tr["vi"]["field_errors"][k], v) for k, v in tr["en"]["field_errors"].items()])

    out += [
        "## Dataset validation issues (`ValidationIssue.code`) / Lỗi kiểm tra dataset",
        "",
        "Key: `validation.issue.<code>`, interpolated with `episode`, `feature`, `path` from the issue.",
        "",
    ]
    issue = {loc: tr[loc]["validation"]["issue"] for loc in tr}
    out += _table(
        [(c, issue["vi"][c], issue["en"][c]) for c in schemas["ValidationIssue"]["properties"]["code"]["enum"]]
    )

    out += [
        "## Run failures (`RunErrorCode`) / Lý do lượt train thất bại",
        "",
        "Key: `run.error.<code>`. Shown on the run detail page above the log excerpt.",
        "",
    ]
    rerr = {loc: tr[loc]["run"]["error"] for loc in tr}
    out += _table([(c, rerr["vi"][c], rerr["en"][c]) for c in schemas["RunErrorCode"]["enum"]])

    out += ["## Run warnings (`RunWarningEvent.code`) / Cảnh báo khi train", "", "Key: `run.warning.<code>`.", ""]
    rw = {loc: tr[loc]["run"]["warning"] for loc in tr}
    out += _table(
        [
            (_key(c), rw["vi"][_key(c)], rw["en"][_key(c)])
            for c in schemas["RunWarningEvent"]["properties"]["code"]["enum"]
        ]
    )

    out += ["## Client-side and generic / Phía trình duyệt và chung", ""]
    out += _table(
        [(f"errors.{k}", err["vi"][k], v) for k, v in err["en"].items() if k not in set(codes)],
        head="| key | vi | en |",
    )
    return "\n".join(out)


def main() -> int:
    repo = Path(__file__).resolve().parents[3]
    target = repo / "docs" / "ux" / "error-catalogue.md"
    text = render(repo)
    if "--check" in sys.argv:
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            print(f"{target} is stale; re-run without --check", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
