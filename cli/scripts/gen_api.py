"""Regenerate ``hibiscus/_generated`` from ``../api/openapi.yaml`` (openapi-python-client).

Usage (from ``cli/``)::

    uv run poe gen-api          # regenerate
    uv run poe check-api        # exit 1 if the committed client is stale

Generated files are never edited by hand (docs/OWNERSHIP.md note 2).
"""

from __future__ import annotations

import argparse
import filecmp
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

CLI_DIR = Path(__file__).resolve().parent.parent
SPEC = CLI_DIR.parent / "api" / "openapi.yaml"
TARGET = CLI_DIR / "hibiscus" / "_generated"
CONFIG = CLI_DIR / "scripts" / "openapi-python-client.yaml"


def _generate(out: Path) -> None:
    exe = shutil.which("openapi-python-client")
    if exe is None:
        sys.exit("openapi-python-client not found; run `uv sync` in cli/")
    cmd = [
        exe,
        "generate",
        "--path",
        str(SPEC),
        "--meta",
        "none",
        "--config",
        str(CONFIG),
        "--output-path",
        str(out),
        "--overwrite",
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, check=False)  # noqa: S603
    if res.returncode != 0 or not (out / "client.py").exists():
        sys.stderr.write(res.stdout + res.stderr)
        sys.exit(f"generation failed (exit {res.returncode})")
    shutil.rmtree(out / ".ruff_cache", ignore_errors=True)
    (out / "README.md").write_text(
        "# Generated — do not edit\n\nGenerated by `uv run poe gen-api` (openapi-python-client) from "
        "`api/openapi.yaml`.\nHand-written wrappers live in `hibiscus/api.py`.\n",
        encoding="utf-8",
    )


def _diff(a: Path, b: Path) -> list[str]:
    out: list[str] = []
    cmp = filecmp.dircmp(a, b, ignore=["__pycache__", ".ruff_cache"])

    def walk(c: filecmp.dircmp[str], rel: str) -> None:
        out.extend(f"{rel}{n} (only in committed)" for n in c.left_only)
        out.extend(f"{rel}{n} (only in fresh)" for n in c.right_only)
        out.extend(f"{rel}{n} (differs)" for n in c.diff_files)
        for name, sub in c.subdirs.items():
            walk(sub, f"{rel}{name}/")

    walk(cmp, "")
    return out


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="only verify, do not write")
    args = parser.parse_args()
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "_generated"
        _generate(fresh)
        if args.check:
            if not TARGET.exists():
                sys.exit("hibiscus/_generated missing; run `uv run poe gen-api`")
            diffs = _diff(TARGET, fresh)
            if diffs:
                sys.stderr.write("\n".join(diffs) + "\n")
                sys.exit("hibiscus/_generated is stale; run `uv run poe gen-api`")
            print("hibiscus/_generated is up to date")
            return
        if TARGET.exists():
            shutil.rmtree(TARGET)
        shutil.copytree(fresh, TARGET, ignore=shutil.ignore_patterns("__pycache__", ".ruff_cache"))
        print(f"generated {TARGET.relative_to(CLI_DIR)}")


if __name__ == "__main__":
    main()
