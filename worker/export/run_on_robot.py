"""Generate ``run_on_robot.sh`` (docs/spec/bundle.md §8).

Every dataset-derived value that reaches the script is either validated against a strict pattern
(camera names, numbers) or shell-quoted with :func:`shlex.quote` (task, robot type), because
dataset metadata is user-controlled input.
"""

from __future__ import annotations

import re
import shlex
from dataclasses import dataclass

from export.lelab_compat import pip_command, required_modules

ROBOT_TYPE_MAP: dict[str, str] = {
    "so_follower": "so101_follower",
    "so101_follower": "so101_follower",
    "so100_follower": "so100_follower",
    "koch_follower": "koch_follower",
}
_CAMERA_RE = re.compile(r"^[A-Za-z][A-Za-z0-9_]{0,63}$")
_REPO_SAFE = re.compile(r"[^A-Za-z0-9_.-]+")


@dataclass(frozen=True)
class CameraSpec:
    key: str  # observation.images.<name>
    width: int
    height: int

    @property
    def name(self) -> str:
        return self.key.removeprefix("observation.images.")


def _fmt_fps(fps: float) -> str:
    return str(int(fps)) if float(fps).is_integer() else repr(float(fps))


def map_robot_type(robot_type: str | None) -> tuple[str, bool]:
    """Return (``--robot.type`` value, verified?)."""
    if robot_type and robot_type in ROBOT_TYPE_MAP:
        return ROBOT_TYPE_MAP[robot_type], True
    return (robot_type or "so101_follower"), False


def render_run_on_robot(
    *,
    bundle_name: str,
    robot_type: str | None,
    fps: float,
    cameras: list[CameraSpec],
    task: str,
    requirements: list[str] | None = None,
) -> str:
    if fps <= 0:
        raise ValueError("fps must be > 0")
    for cam in cameras:
        if not _CAMERA_RE.match(cam.name):
            raise ValueError(f"camera name {cam.name!r} is not a safe identifier ([A-Za-z][A-Za-z0-9_]*)")
        if cam.width <= 0 or cam.height <= 0:
            raise ValueError(f"camera {cam.name}: invalid size {cam.width}x{cam.height}")
    rtype, known = map_robot_type(robot_type)
    fps_s = _fmt_fps(fps)
    cam_vars = [(cam, cam.name.upper()) for cam in cameras]
    cam_defaults = "\n".join(
        f'{var}="${{{var}:-{i}}}"  # camera index or /dev/videoN for {cam.key}'
        for i, (cam, var) in enumerate(cam_vars)
    )
    cam_entries = ", ".join(
        f"{cam.name}: {{type: opencv, index_or_path: ${{{var}}}, "
        f"width: {cam.width}, height: {cam.height}, fps: {fps_s}}}"
        for cam, var in cam_vars
    )
    cameras_arg = f'--robot.cameras="{{ {cam_entries} }}"' if cameras else ""
    todo = "" if known else "# TODO(user): verify --robot.type (dataset robot_type was not recognised)\n"
    eval_repo = "local/eval_" + _REPO_SAFE.sub("_", bundle_name)
    task_q = shlex.quote(task)
    rtype_q = shlex.quote(rtype)

    lines = [
        "#!/usr/bin/env bash",
        f"# Generated by Hibiscus for {bundle_name}. "
        "Edit PORT / camera indices, then run inside the LeLab venv:",
        "#   source ~/lelab/leLab/.venv/bin/activate && ./run_on_robot.sh",
        "set -euo pipefail",
        'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
        'PORT="${PORT:-/dev/ttyACM0}"            # robot serial port (the only value you must edit)',
        'ROBOT_ID="${ROBOT_ID:-my_follower}"     # must match your calibration id',
    ]
    if requirements:
        # QC-ml-1: this policy needs packages the LeLab venv lacks; say so before lerobot does.
        pip = pip_command(requirements)
        checks = " ".join(f"import {m};" for m in required_modules(requirements))
        lines += [
            f"# Requires (not in the LeLab venv): {pip}",
            f"if ! python -c {shlex.quote(checks)} 2>/dev/null; then",
            f'  echo "This policy needs extra packages. Inside the LeLab venv run: {pip}" >&2',
            "  exit 1",
            "fi",
        ]
    if cam_defaults:
        lines.append(cam_defaults)
    if todo:
        lines.append(todo.rstrip("\n"))
    rollout = [
        "lerobot-rollout \\",
        "  --strategy.type=base \\",
        '  --policy.path="$HERE/pretrained_model" \\',
        f"  --robot.type={rtype_q} \\",
        '  --robot.port="$PORT" --robot.id="$ROBOT_ID" \\',
    ]
    if cameras_arg:
        rollout.append(f"  {cameras_arg} \\")
    rollout += [
        f"  --task={task_q} \\",
        f'  --fps={fps_s} --duration="${{DURATION:-60}}"',
    ]
    lines += rollout
    # LeRobot 0.7.1's lerobot-record has no policy option ("for policy-based deployment, use
    # lerobot-rollout"); recording evaluation episodes is lerobot-rollout's episodic strategy
    # (CR-A5-3 corrects bundle.md §8 accordingly).
    record = [
        "",
        "# --- Variant: record evaluation episodes with the policy -----------------------------------",
        "# (LeRobot 0.7.1: lerobot-record does not take --policy.path; use the episodic rollout strategy)",
        "# lerobot-rollout \\",
        "#   --strategy.type=episodic \\",
        '#   --policy.path="$HERE/pretrained_model" \\',
        f"#   --robot.type={rtype_q} \\",
        '#   --robot.port="$PORT" --robot.id="$ROBOT_ID" \\',
    ]
    if cameras_arg:
        record.append(f"#   {cameras_arg} \\")
    record += [
        f"#   --dataset.repo_id={eval_repo} \\",
        f"#   --dataset.single_task={task_q} \\",
        f"#   --dataset.fps={round(fps)} --dataset.num_episodes=10 --dataset.episode_time_s=60 \\",
        f"#   --fps={fps_s} --dataset.push_to_hub=false",
    ]
    lines += record
    return "\n".join(lines) + "\n"
