"""API <-> Cloudflare Email Worker wire contract (SEC-infra-1).

The fixture ``deploy/cloudflare/email-worker/test/fixtures/api-send-requests.json`` holds the exact
bytes and signature :class:`CloudflareWorkerEmailSender` emits for a few messages. This test pins
the API side to it; the Worker's ``test/worker.test.ts`` feeds the very same requests through its
real ``handle()`` and requires 202. Changing the body shape on one side without the other now fails
a test instead of silently breaking every transactional email in production.

Regenerate after a deliberate protocol change (then run the Worker tests, ``make email-worker-check``)::

    HIBISCUS_REGEN_EMAIL_FIXTURE=1 uv run pytest tests/contract/test_email_worker_contract.py
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import httpx
import pytest

from app.core.email import (
    SIGNATURE_HEADER,
    TIMESTAMP_HEADER,
    CloudflareWorkerEmailSender,
    EmailMessage,
    verify_signature,
)

REPO = Path(__file__).resolve().parents[3]
FIXTURE = REPO / "deploy" / "cloudflare" / "email-worker" / "test" / "fixtures" / "api-send-requests.json"

SECRET = "0123456789abcdef0123456789abcdef0123456789abcdef"  # >= 32 chars, as the Worker requires
TIMESTAMP = 1794738600
SENDER = "Hibiscus <no-reply@robot.example.com>"
CASES: list[dict[str, Any]] = [
    {
        "name": "text and html",
        "message": {
            "to": "alice@example.org",
            "subject": "Xác thực email Hibiscus",
            "text": "Mã xác thực: 123456\nhttps://robot.example.com/verify-email#token=abc",
            "html": "<p>Mã xác thực: <b>123456</b></p>",
            "message_id": "6f1c2a8e-3b7d-4e0a-9a51-0c2d7f4b8e19",
        },
    },
    {
        "name": "text only (html is null)",
        "message": {
            "to": "bob.smith+tag@sub.example.co",
            "subject": "Lời mời tham gia workspace",
            "text": "Bạn được mời: https://robot.example.com/invite#token=xyz",
            "html": None,
            "message_id": "0b9a3c4d-1e2f-4a5b-8c6d-7e8f9a0b1c2d",
        },
    },
]


async def _emit(case: dict[str, Any], monkeypatch: pytest.MonkeyPatch) -> httpx.Request:
    captured: list[httpx.Request] = []

    def handler(request: httpx.Request) -> httpx.Response:
        captured.append(request)
        return httpx.Response(202, json={"status": "sent"})

    monkeypatch.setattr("app.core.email.time.time", lambda: float(TIMESTAMP))
    sender = CloudflareWorkerEmailSender(
        "https://email.example.workers.dev/send", SECRET, SENDER, transport=httpx.MockTransport(handler)
    )
    await sender.send(EmailMessage(**case["message"]))
    assert len(captured) == 1
    return captured[0]


async def test_api_emits_exactly_the_fixture_requests(monkeypatch: pytest.MonkeyPatch) -> None:
    produced = []
    for case in CASES:
        req = await _emit(case, monkeypatch)
        assert req.method == "POST"
        assert req.headers["content-type"] == "application/json"
        assert verify_signature(
            SECRET, req.headers[TIMESTAMP_HEADER], req.content, req.headers[SIGNATURE_HEADER], now=TIMESTAMP
        )
        produced.append(
            {
                "name": case["name"],
                "timestamp": req.headers[TIMESTAMP_HEADER],
                "signature": req.headers[SIGNATURE_HEADER],
                "body": req.content.decode("utf-8"),
                "expect": {
                    "to": case["message"]["to"],
                    "subject": case["message"]["subject"],
                    "text": case["message"]["text"],
                    "html": case["message"]["html"],
                },
            }
        )
    doc = {
        "_comment": "Generated by backend/tests/contract/test_email_worker_contract.py; consumed by "
        "deploy/cloudflare/email-worker/test/worker.test.ts. Do not edit by hand.",
        "secret": SECRET,
        "sender": SENDER,
        "requests": produced,
    }
    if os.environ.get("HIBISCUS_REGEN_EMAIL_FIXTURE") == "1":
        FIXTURE.parent.mkdir(parents=True, exist_ok=True)
        FIXTURE.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    pinned = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert pinned == doc, (
        "CloudflareWorkerEmailSender's wire format changed: update the Email Worker "
        "(deploy/cloudflare/email-worker/src/message.ts) and regenerate the shared fixture "
        "(HIBISCUS_REGEN_EMAIL_FIXTURE=1)"
    )
